import os
import smtplib
from email.message import EmailMessage

def send_alert_email(pdf_path, config):
    """
    Constructs a MIME email message with the PDF audit report attached
    and dispatches it securely via SMTP.
    """
    smtp_server = config.get("smtp_server", "smtp.example.com")
    smtp_port = config.get("smtp_port", 587)
    sender_email = config.get("sender_email", "alerts@localdomain.internal")
    recipient_email = config.get("recipient_email", "admin@localdomain.internal")
    
    # In production, use environment variables for sensitive auth credentials:
    # email_pass = os.environ.get("SMTP_PASSWORD", "")

    msg = EmailMessage()
    msg['Subject'] = "🚨 Automated Alert: Endpoint Health & Security Triage Report"
    msg['From'] = sender_email
    msg['To'] = recipient_email
    
    msg.set_content(
        "Hello Engineer,\n\n"
        "Please find attached the automated daily endpoint health and security "
        "audit report generated by your triage pipeline.\n\n"
        "Review the attached PDF for threshold breaches and security anomaly indicators.\n\n"
        "---\nEndpoint Health & Security Triage Automation"
    )

    # Attach the PDF Report if it exists
    if os.path.exists(pdf_path):
        try:
            with open(pdf_path, 'rb') as f:
                file_data = f.read()
                file_name = os.path.basename(pdf_path)
            
            msg.add_attachment(
                file_data,
                maintype='application',
                subtype='pdf',
                filename=file_name
            )
            print(f"[+] Attached PDF report: {file_name}")
        except Exception as e:
            print(f"[-] Failed to attach PDF report: {e}")
    else:
        print(f"[-] PDF report not found at {pdf_path}. Sending email without attachment.")

    # SMTP Dispatch (Wrapped in try/except for safe testing)
    try:
        print(f"[*] Connecting to SMTP server {smtp_server}:{smtp_port}...")
        # To test live servers, uncomment below:
        # with smtplib.SMTP(smtp_server, smtp_port) as server:
        #     server.starttls()
        #     # server.login(sender_email, email_pass)
        #     server.send_message(msg)
        print("[+] Email alert dispatch simulated successfully.")
        return True
    except Exception as e:
        print(f"[-] SMTP connection failed: {e}")
        return False

if __name__ == "__main__":
    sample_config = {
        "smtp_server": "smtp.example.com",
        "smtp_port": 587,
        "sender_email": "alerts@localdomain.internal",
        "recipient_email": "admin@localdomain.internal"
    }
    send_alert_email("daily_triage_report.pdf", sample_config)
